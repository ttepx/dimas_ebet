def compose_rules(n: int = 5) -> str:
    rules = random.sample(CHAT_RULES, k=min(n, len(CHAT_RULES)))
    lines = "\n".join(f"{i}. {r}" for i, r in enumerate(rules, 1))
    return f"📜 <b>Нові правила чату (діють негайно й назавжди):</b>\n\n{lines}"


# Відмови нейромереж: шукаємо їх розумно, а не по будь-якому слову «cannot» у тексті
_REFUSAL = re.compile(
    r"(i('m| am) (sorry|unable|not able)|i can('|no)t (help|assist|comply|provide|fulfill|do that)|"
    r"as an ai|i won'?t (be able|help)|не можу (допомогти|виконати|цього зробити|генерувати|відповісти)|"
    r"не буду (цього|це)|вибач(те)?,? (але )?я|на жаль,? я не|порушує (правила|політик)|"
    r"не (можу|маю права) (створювати|писати|генерувати) (контент|матеріал))",
    re.IGNORECASE,
)


def looks_like_refusal(text: str) -> bool:
    t = text.strip().lower().translate(str.maketrans({"’": "'", "‘": "'", "ʼ": "'", "＇": "'"}))
    if not t:
        return True
    head = t[:160]
    if len(t) < 350 and _REFUSAL.search(t):
        return True
    return bool(_REFUSAL.match(head))
